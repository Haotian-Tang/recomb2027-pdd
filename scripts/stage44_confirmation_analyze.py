#!/usr/bin/env python3
"""Post-measurement report and integrity checks; never executes a solver."""
from collections import Counter, defaultdict
from fractions import Fraction as F
import csv
import json
from pathlib import Path
from statistics import median
from stage42_benchmark import independent_geometry, sha, verify
ROOT = Path(__file__).resolve().parents[1]
P = ROOT / 'results/stage44_confirmation_protocol.json'
R = ROOT / 'results/stage44_confirmation.json'
protocol, result = json.loads(P.read_text()), json.loads(R.read_text())
assert result['protocol_sha256'] == sha(P)
for name, expected in protocol['script_hashes'].items():
    assert sha(ROOT / 'scripts' / name) == expected, name
stream = [json.loads(line) for line in (ROOT / 'results/stage44_confirmation_runs.jsonl').read_text().splitlines()]
lookup = {(r['name'], r['repetition'], r['method']): r['result'] for r in stream}
assert len(lookup) == len(stream) == 256

shapes = defaultdict(set)
def signature(edges):
    adjacency, _ = independent_geometry(edges)
    def rooted(v, parent):
        return '(' + ''.join(sorted(rooted(u, v) for u, _ in adjacency[v] if u != parent)) + ')'
    return min(rooted(v, None) for v in adjacency)

checks, stable, unknown_cases, identified = 0, True, [], Counter()
csv_rows = []
for encoded, record in zip(protocol['cases'], result['records']):
    assert encoded['name'] == record['name']
    case = dict(encoded)
    case['edges'] = [(u, v, F(ell)) for u, v, ell in case['edges']]
    case['observed'] = {int(r): F(d) for r, d in case['observed'].items()}
    shapes[case['original_leaves']].add(signature(case['edges']))
    completed_answers = set()
    for method in protocol['methods'][case['task']]:
        runs = [rep['runs'][method] for rep in record['repetitions']]
        stability = {(v['status'], v.get('feasible'), v.get('minimum')) for v in runs}
        stable &= len(stability) == 1
        for rep, measured in zip(record['repetitions'], runs):
            assert lookup[case['name'], rep['repetition'], method] == measured
            if measured['status'] == 'complete':
                completed_answers.add((measured['feasible'], measured['minimum']))
            if 'witness' in measured:
                assert verify(case, measured['witness']) == measured['minimum']
                if case['task'] == 'fixed_one_missing':
                    assert F(measured['witness']['pendant']) == F(case['pendant'])
                checks += 1
        csv_rows.append(dict(name=case['name'], task=case['task'], group=case['group'],
            n_leaves=case['original_leaves'], cap=case['cap'], generating_count=case['generating_count'],
            missing_leaves=len(case['hidden_leaves']), method=method,
            rep1_status=runs[0]['status'], rep2_status=runs[1]['status'],
            minimum_if_complete=runs[0].get('minimum') if runs[0]['status'] == 'complete' else '',
            median_cpu_if_both_complete=median(v['child_cpu_seconds'] for v in runs)
                if all(v['status'] == 'complete' for v in runs) else '',
            rep1_cpu_seconds=runs[0]['child_cpu_seconds'], rep2_cpu_seconds=runs[1]['child_cpu_seconds']))
    assert len(completed_answers) <= 1
    if not completed_answers:
        unknown_cases.append(case['name'])
        identified['unknown'] += 1
    else:
        feasible, minimum = next(iter(completed_answers))
        identified['feasible' if feasible else 'infeasible_within_cap'] += 1
assert stable and checks == 192
with (ROOT / 'results/stage44_confirmation_table.csv').open('w') as handle:
    writer = csv.DictWriter(handle, fieldnames=list(csv_rows[0]))
    writer.writeheader()
    writer.writerows(csv_rows)

lines = ['# Stage44: new-instance confirmation of frozen exact PDD prototypes', '',
'14 October 2026. All earlier stages are frozen. No solver was tuned using these results.', '',
'## Protocol frozen before timing', '',
f'The immutable protocol SHA-256 is `{sha(P)}`. It records 48 complete exact inputs, seed '
'`4410142026`, and hashes of all 16 transitively imported local Python source files. '
'Input generation and arithmetic verification called no solver or support oracle before registration.', '',
'There are 32 free-pendant and 16 prescribed-pendant/exactly-one-missing cases. Each original tree '
'is generated by successive random edge insertion into a three-leaf star, with randomized edge '
'orientations and unequal positive rational lengths. Leaf counts are 6, 8, 10, and 12; source '
'budgets are 2–5. Source locations and positive weights are rational, with both internal and '
'leaf-incident edges represented. Free-pendant missingness includes zero, one, roughly one third, '
'and half of original leaves. Exactly half of the fixed-one generators include a source on the '
'hidden edge. Half the inputs use cap+1 generating sources; this is a tighter budget, **not an '
'assumption of infeasibility or of identifiable generating composition**.', '',
f'Across both tasks the generated unlabelled topology counts by leaf count are '
+ ', '.join(f'n={n}: {len(v)}' for n, v in sorted(shapes.items())) + '. '
'No case was removed, replaced, or selected according to a solver output. One free-pendant input '
'has minimum one even though generated from three sources; it remains in the results.', '',
'Each case/method has two repetitions: 256 jobs total. Each fresh Linux child has a 2 s '
'whole-process hard wall cap and 1 GiB address-space cap. Method order rotates and reverses '
'according to the frozen rule. Imports and generation are excluded; existing internal solver '
'diagnostics remain included. Child CPU is user+system from `wait4`, distinct from the wall cap. '
'Independent original-tree witness verification occurs after timing. Every timeout remains '
'UNKNOWN. All 256 raw jobs are retained in JSON and a JSONL stream.', '',
'## Completion and correctness', '',
'| Task | Method | Cases completed in both repetitions | Timeout jobs | Valid returned witnesses |',
'|---|---|---:|---:|---:|']
labels = {'original_support': 'Original-support enumeration', 'stage41_active_basis': 'S0: Stage41 active bases',
    'stage43_equality_reduced': 'S1: Stage43 equality reduction', 'original_fixed_oracle': 'Original fixed-pendant oracle',
    'stage43_fixed_one': 'Stage43 fixed-one structural solver'}
for task, data in result['summary']['tasks'].items():
    for method, stats in data['methods'].items():
        lines.append(f'| {task} | {labels[method]} | {stats["cases_complete_both_repetitions"]}/{data["cases"]} '
            f'| {stats["status_counts"].get("unknown", 0)} | {stats["verified_witnesses"]} |')
lines += ['', 'All completed exact answers agree within and between repetitions and methods. '
'Every method has the same complete/unknown outcome in both repetitions on every case. '
'All **192 returned witnesses** reproduce the original observations exactly; all fixed-pendant '
'witnesses also match the prescribed pendant exactly. No solver error or failed witness was observed.', '',
'The new free-pendant solver completes all 32 cases. Its answer is independently matched by '
'original-support enumeration on 30, and by S0 on 24; 31/32 are matched by at least one other '
'algorithm. `free_random_27_n10_cap5_g6_missing1` is completed only by S1 (minimum five): '
'its witness is verified, but the minimality conclusion is not independently completed under '
'the common cap.', '',
'For fixed-one, the two methods jointly finish 12/16 cases. The structural solver completes '
'13/16 while the oracle completes 14/16. They therefore complement each other; this experiment '
'does not support universal practical superiority of the new fixed-one implementation. Across '
'both tasks, at least one method establishes 39 feasible and eight infeasible-within-budget '
'cases; one case remains unknown for every method under the primary 2 s cap. These are exact finite-input conclusions, '
'not biological validation.', '',
'## Timing on jointly completed cases only', '',
'For each method/case, first take the median CPU of its two repetitions. The following rows use '
'only cases where both compared methods finish both repetitions. Median ratios are medians of '
'casewise ratios, not ratios of the two median times. No timed-out value is imputed.', '',
'| Task | First / second method | Joint cases | Median CPU first / second (s) | Median case ratio first/second | Cases faster: first / second |',
'|---|---|---:|---:|---:|---:|']
for task, data in result['summary']['tasks'].items():
    for pair, stats in data['pairwise'].items():
        a, b = pair.split(' vs ')
        vals = stats['median_case_cpu_seconds']
        lines.append(f'| {task} | {labels[a]} / {labels[b]} | {stats["joint_complete_both_repetitions"]} '
            f'| {vals[a]:.6f} / {vals[b]:.6f} | {stats["median_case_ratio_first_over_second"]:.3f} '
            f'| {stats["first_lower_cpu_cases"]} / {stats["second_lower_cpu_cases"]} |')
lines += ['', 'Completion selection matters: the 24 S0/S1 jointly completed cases exclude the '
'eight cases where S0 timed out. Total CPU including killed children is available in raw results '
'but is not an uncensored speedup estimate. Two repetitions and these small synthetic inputs '
'do not justify confidence intervals, large-scale performance claims, or population-level '
'speed claims.', '', '## Reversals and unresolved inputs retained', '',
'| Case | First method | Second method | Interpretation |', '|---|---:|---:|---|']
selected = [
    ('free_random_15_n12_cap5_g5_missing4', 'original_support', 'stage43_equality_reduced', 'S1 is slower despite both returning minimum 3.'),
    ('fixed_random_03_n6_cap5_g5_hidden0', 'original_fixed_oracle', 'stage43_fixed_one', 'Structural solver is much slower; both return minimum 3.'),
    ('fixed_random_07_n8_cap5_g5_hidden0', 'original_fixed_oracle', 'stage43_fixed_one', 'Oracle proves minimum 4; structural solver times out twice.'),
    ('fixed_random_11_n10_cap5_g6_hidden0', 'original_fixed_oracle', 'stage43_fixed_one', 'Oracle proves minimum 4; structural solver times out twice.'),
    ('fixed_random_14_n12_cap4_g5_hidden1', 'original_fixed_oracle', 'stage43_fixed_one', 'Structural solver reports infeasible within cap 4; oracle times out twice, so no independent completed NO check.'),
    ('fixed_random_15_n12_cap5_g6_hidden0', 'original_fixed_oracle', 'stage43_fixed_one', 'Both time out twice; feasibility and minimum remain unresolved under the primary 2 s cap.')]
by_name = {r['name']: r for r in result['records']}
for name, first, second, interpretation in selected:
    r = by_name[name]
    values = []
    for method in (first, second):
        runs = [rep['runs'][method] for rep in r['repetitions']]
        values.append(f'{median(v["child_cpu_seconds"] for v in runs):.6f} CPU s'
            if all(v['status'] == 'complete' for v in runs) else 'UNKNOWN at 2 s wall cap')
    lines.append(f'| `{name}` | {values[0]} | {values[1]} | {interpretation} |')
lines += ['', 'The improvement from equality reduction therefore has new-instance support for the '
'free-pendant implementation, while the fixed-one extension exposes a remaining search cost. '
'No solver optimization or repeat of the primary timing protocol was performed after inspecting these outcomes. A separately registered posthoc correctness-only extension is documented in `review/stage44_confirmation_posthoc.md`; it never changes the primary completion table or timing ratios. The theoretical '
'contribution is the structural/parameterized classification; ordinary LP preprocessing is '
'implementation work, and this finite experiment is not an originality test.', '',
'## Files and reproduction', '',
'- `scripts/stage44_confirmation.py`: frozen generator and timing driver.',
'- `results/stage44_confirmation_protocol.json`: exact inputs and preregistered source hashes.',
'- `results/stage44_confirmation.json`: every method/repetition and summary.',
'- `results/stage44_confirmation_runs.jsonl`: append-only raw job stream.',
'- `results/stage44_confirmation_table.csv`: one row per case/method, including both statuses and times.',
'- `scripts/stage44_confirmation_analyze.py`: post-measurement integrity checks and report generation; runs no solver.',
'- `results/stage44_confirmation_integrity.json`: hash, stream, witness and repetition checks.', '',
'Run `.venv/bin/python scripts/stage44_confirmation_analyze.py` to recheck the saved results. '
'The timing driver intentionally refuses to overwrite either registered inputs or measured '
'results. A timing replication belongs in a separate copy/destination with the frozen protocol '
'and sources retained. This report describes a locally preregistered experiment, not external '
'preregistration or independent human validation.', '']
report = ROOT / 'review/stage44_confirmation.md'
report.write_text('\n'.join(lines))
integrity = dict(status='PASS', protocol_sha256=sha(P), result_sha256=sha(R),
    source_hashes_rechecked=len(protocol['script_hashes']), jsonl_jobs_reconciled=len(stream),
    independent_witnesses_reverified=checks, same_outcome_both_repetitions=stable,
    exact_input_outcomes=dict(identified), unknown_for_every_method=unknown_cases,
    distinct_unlabelled_shapes_by_leaf_count={str(n): len(v) for n, v in sorted(shapes.items())},
    report_sha256=sha(report), caveat='PASS covers finite integrity/agreement checks, not completion of all tasks or proof of correctness')
(ROOT / 'results/stage44_confirmation_integrity.json').write_text(json.dumps(integrity, indent=2) + '\n')
print(json.dumps(integrity, indent=2))
